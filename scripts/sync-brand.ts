import { readFile, writeFile, copyFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { createHash } from "node:crypto";

const source = resolve(process.env.RAKKY_SOURCE ?? "../ride_app");
const palettePath = resolve(source, "mobile/src/constants/colors.ts");
const { lightColors, darkColors } = (await import(
  pathToFileURL(palettePath).href
)) as {
  lightColors: Record<string, string>;
  darkColors: Record<string, string>;
};
function declarations(tokens: Record<string, string>) {
  return Object.entries(tokens)
    .map(([name, value]) => `  --${name}: ${value};`)
    .join("\n");
}
const hash = createHash("sha256")
  .update(await readFile(palettePath))
  .digest("hex");
await writeFile(
  "src/app/brand.generated.css",
  `/* Generated by npm run sync:brand from ride_app/mobile/src/constants/colors.ts. Do not edit. Source SHA256: ${hash} */\n:root {\n${declarations(lightColors)}\n}\n:root[data-theme="dark"] {\n${declarations(darkColors)}\n}\n`,
);
await mkdir("public/brand", { recursive: true });
await mkdir("public/fonts", { recursive: true });
await copyFile(
  resolve(source, "mobile/assets/images/brand/rakky-ride-logo.png"),
  "public/brand/rakky-ride-logo.png",
);
for (const [folder, file] of [
  ["400Regular", "Inter_400Regular.ttf"],
  ["600SemiBold", "Inter_600SemiBold.ttf"],
  ["700Bold", "Inter_700Bold.ttf"],
]) {
  await copyFile(
    resolve(
      source,
      `mobile/node_modules/@expo-google-fonts/inter/${folder}/${file}`,
    ),
    `public/fonts/${file}`,
  );
}
await copyFile(
  resolve(source, "mobile/node_modules/@expo-google-fonts/inter/LICENSE_FONT"),
  "public/fonts/OFL.txt",
);
console.log("Brand tokens, canonical logo and Inter fonts synchronized.");
